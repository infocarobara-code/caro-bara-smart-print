export type BookingCopy = typeof bookingCopy.de;
export function errorCopy(code: string, t: BookingCopy) {
  return code === "SLOT_UNAVAILABLE" || code === "STATE_CONFLICT"
    ? t.conflict
    : code === "INVALID_INPUT"
      ? t.invalid
      : code === "TOO_MANY_REQUESTS"
        ? t.limited
        : code === "CODE_NOT_FOUND"
          ? t.notFound
          : code === "BOOKING_UNAVAILABLE"
            ? t.unavailable
            : t.generic;
}
